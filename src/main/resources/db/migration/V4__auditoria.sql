-- V4: auditoría y ordenamiento para el esquema real de PharmaBackend.
alter table categorias add (creado_por varchar2(50 char), modificado_por varchar2(50 char));
alter table producto add (creado_por varchar2(50 char), modificado_por varchar2(50 char));
alter table clientes add (creado_por varchar2(50 char), modificado_por varchar2(50 char));
alter table ventas add (creado_por varchar2(50 char));

create table auditoria_eventos (
    id number(19,0) generated by default as identity,
    fecha timestamp(6) not null, usuario varchar2(50 char) not null,
    accion varchar2(40 char) not null, entidad varchar2(40 char) not null,
    entidad_id number(19,0), detalle varchar2(500 char), request_id varchar2(36 char),
    constraint pk_auditoria_eventos primary key (id)
);
create index ix_auditoria_fecha on auditoria_eventos(fecha);
create index ix_auditoria_usuario on auditoria_eventos(usuario, fecha);
create index ix_productos_nombre on producto(nombre);
create index ix_ventas_fecha on ventas(fecha, id);
